import { invoke } from "@tauri-apps/api/core";
import type {
  AdjustBatchInput,
  AuthStatus,
  Batch,
  Category,
  InventoryBatch,
  InventoryItem,
  NewProduct,
  NewSupplier,
  ProductHit,
  PurchaseInvoice,
  PurchaseResult,
  ReceiveBatchInput,
  SaleDraft,
  SaleResult,
  SearchMode,
  Supplier,
  User,
} from "../core/types.ts";
import type { PharmacyRepo } from "./repo.ts";

export const tauriRepo: PharmacyRepo = {
  kind: "sqlite",
  authStatus: () => invoke<AuthStatus>("auth_status"),
  setupAdmin: (password: string) => invoke<User>("setup_admin", { password }),
  login: (username: string, password: string) => invoke<User>("login", { username, password }),
  logout: () => invoke<void>("logout"),
  search: (query: string, mode: SearchMode) => invoke<ProductHit[]>("search_products", { query, mode }),
  findByCode: (codes: string[]) => invoke<ProductHit | null>("find_by_code", { codes }),
  alternatives: (productId: string) => invoke<ProductHit[]>("alternatives", { productId }),
  batches: (productId: string) => invoke<Batch[]>("product_batches", { productId }),
  postSale: (draft: SaleDraft) => invoke<SaleResult>("post_sale", { draft }),
  inventory: () => invoke<InventoryItem[]>("inventory_list"),
  inventoryBatches: (productId: string) => invoke<InventoryBatch[]>("inventory_batches", { productId }),
  categories: () => invoke<Category[]>("list_categories"),
  addProduct: (product: NewProduct) => invoke<InventoryItem>("add_product", { product }),
  receiveBatch: (batch: ReceiveBatchInput) => invoke<InventoryItem>("receive_batch", { batch }),
  adjustBatch: (adjustment: AdjustBatchInput) => invoke<InventoryItem>("adjust_batch", { adjustment }),
  suppliers: () => invoke<Supplier[]>("list_suppliers"),
  addSupplier: (supplier: NewSupplier) => invoke<Supplier>("add_supplier", { supplier }),
  postPurchaseInvoice: (invoice: PurchaseInvoice) => invoke<PurchaseResult>("post_purchase_invoice", { invoice }),
};
