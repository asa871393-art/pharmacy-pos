import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import type { PermissionOverrides } from "../core/permissions.ts";
import type {
  AdjustBatchInput,
  AuthStatus,
  Batch,
  Category,
  ExpiryReport,
  InventoryBatch,
  InventoryItem,
  NewProduct,
  NewSupplier,
  NewUser,
  PhoneScan,
  PhoneScannerInfo,
  ProductHit,
  PurchaseInvoice,
  PurchaseResult,
  ReceiveBatchInput,
  ReorderRow,
  ReportFilter,
  Role,
  RxReport,
  SaleDraft,
  SaleResult,
  SalesReport,
  SearchMode,
  Supplier,
  User,
  UserRef,
  UserRow,
} from "../core/types.ts";
import type { PharmacyRepo } from "./repo.ts";

export const tauriRepo: PharmacyRepo = {
  kind: "sqlite",
  authStatus: () => invoke<AuthStatus>("auth_status"),
  setupAdmin: (password: string) => invoke<User>("setup_admin", { password }),
  login: (username: string, password: string) => invoke<User>("login", { username, password }),
  logout: () => invoke<void>("logout"),
  search: (query: string, mode: SearchMode) => invoke<ProductHit[]>("search_products", { query, mode }),
  findByCode: (codes: string[]) => invoke<ProductHit | null>("find_by_code", { codes }),
  alternatives: (productId: string) => invoke<ProductHit[]>("alternatives", { productId }),
  batches: (productId: string) => invoke<Batch[]>("product_batches", { productId }),
  postSale: (draft: SaleDraft) => invoke<SaleResult>("post_sale", { draft }),
  inventory: () => invoke<InventoryItem[]>("inventory_list"),
  inventoryBatches: (productId: string) => invoke<InventoryBatch[]>("inventory_batches", { productId }),
  categories: () => invoke<Category[]>("list_categories"),
  addProduct: (product: NewProduct) => invoke<InventoryItem>("add_product", { product }),
  receiveBatch: (batch: ReceiveBatchInput) => invoke<InventoryItem>("receive_batch", { batch }),
  adjustBatch: (adjustment: AdjustBatchInput) => invoke<InventoryItem>("adjust_batch", { adjustment }),
  suppliers: () => invoke<Supplier[]>("list_suppliers"),
  addSupplier: (supplier: NewSupplier) => invoke<Supplier>("add_supplier", { supplier }),
  postPurchaseInvoice: (invoice: PurchaseInvoice) => invoke<PurchaseResult>("post_purchase_invoice", { invoice }),
  reportUsers: () => invoke<UserRef[]>("report_users"),
  reportSales: (filter: ReportFilter) => invoke<SalesReport>("report_sales", { filter }),
  reportExpiry: (filter: ReportFilter, withinDays: number) => invoke<ExpiryReport>("report_expiry", { filter, withinDays }),
  reportReorder: (categoryId?: string) => invoke<ReorderRow[]>("report_reorder", { categoryId: categoryId ?? null }),
  reportPrescriptions: (filter: ReportFilter) => invoke<RxReport>("report_prescriptions", { filter }),
  saveExport: (fileName: string, content: string) => invoke<string>("save_export", { fileName, content }),
  listUsers: () => invoke<UserRow[]>("list_users"),
  createUser: (user: NewUser) => invoke<UserRow>("create_user", { user }),
  updateUserRole: (userId: string, role: Role, overrides: PermissionOverrides) =>
    invoke<UserRow>("update_user_role", { userId, role, overrides }),
  toggleUserStatus: (userId: string, active: boolean) => invoke<UserRow>("toggle_user_status", { userId, active }),
  resetUserPassword: (userId: string, password: string) => invoke<UserRow>("reset_user_password", { userId, password }),
  phoneScanner: () => invoke<PhoneScannerInfo>("phone_scanner_info"),
  onPhoneScan: (handler: (scan: PhoneScan) => void) => listen<PhoneScan>("phone-barcode-scanned", (e) => handler(e.payload)),
};
